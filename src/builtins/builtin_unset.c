#include "minishell.h"

int	builtin_unset(t_shell *shell, char **argv)
{
	size_t	i;

	if (!shell || !argv)
		return (1);
	i = 1;
	while (argv[i])
	{
		if (env_unset(&shell->env, argv[i]) == -1)
			return (1);
		i++;
	}
	return (0);
}
