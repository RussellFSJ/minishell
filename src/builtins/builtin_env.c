#include "minishell.h"

int	builtin_env(t_shell *shell)
{
	t_env	*env;

	if (!shell)
		return (1);
	env = shell->env;
	while (env)
	{
		if (env->exported && env->value)
		{
			ft_putstr_fd(env->key, 1);
			ft_putchar_fd('=', 1);
			ft_putendl_fd(env->value, 1);
		}
		env = env->next;
	}
	return (0);
}
